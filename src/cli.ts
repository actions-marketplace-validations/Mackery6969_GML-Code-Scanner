export function main(argv: string[]): number {
  let args;
  try {
    args = parseArgs({
      args: argv,
      allowPositionals: true,
      options: {
        format: { type: "string", short: "f" },
        output: { type: "string", short: "o" },
        sarif: { type: "string" },
        paths: { type: "boolean" },
        "no-color": { type: "boolean" },
        config: { type: "string", short: "c" },
        suite: { type: "string" },
        rule: { type: "string", multiple: true },
        runtime: { type: "string" },
        "threat-model": { type: "string", multiple: true },
        "fail-on": { type: "string" },
        "list-rules": { type: "boolean" },
        init: { type: "boolean" },
        version: { type: "boolean", short: "v" },
        help: { type: "boolean", short: "h" },
      },
    });
  } catch (e) {
    process.stderr.write(`gmlscan: ${(e as Error).message}\n\n${HELP}`);
    return 2;
  }
  const o = args.values;
  if (o.help) {
    process.stdout.write(HELP);
    return 0;
  }
  if (o.version) {
    process.stdout.write(`${VERSION}\n`);
    return 0;
  }
  if (o["list-rules"]) {
    const text = listRules(o.format ?? "text");
    if (o.output) {
      mkdirSync(dirname(resolve(o.output)), { recursive: true });
      writeFileSync(o.output, text);
    } else process.stdout.write(text);
    return 0;
  }
  const root = resolve(args.positionals[0] ?? ".");
  if (!existsSync(root)) {
    process.stderr.write(`gmlscan: path not found: ${root}\n`);
    return 2;
  }
  if (o.init) {
    const target = join(root, CONFIG_FILE_NAMES[0]);
    if (existsSync(target)) {
      process.stderr.write(`gmlscan: ${target} already exists\n`);
      return 2;
    }
    writeFileSync(target, STARTER_CONFIG);
    process.stdout.write(`Wrote ${target}\n`);
    return 0;
  }

  const format = o.format ?? "text";
  if (!["text", "json", "sarif"].includes(format)) {
    process.stderr.write(`gmlscan: unknown format "${format}" (expected text, json or sarif)\n`);
    return 2;
  }
  const failOn = o["fail-on"] ?? "error";
  if (!["error", "warning", "note", "none"].includes(failOn)) {
    process.stderr.write(`gmlscan: --fail-on must be error, warning, note or none\n`);
    return 2;
  }
  const suites = ["default", "security-extended", "security-and-quality", "all"];
  if (o.suite && !suites.includes(o.suite)) {
    process.stderr.write(`gmlscan: --suite must be one of ${suites.join(", ")}\n`);
    return 2;
  }
  const threats = o["threat-model"];
  if (threats?.some((t) => t !== "remote" && t !== "local")) {
    process.stderr.write(`gmlscan: --threat-model must be remote or local\n`);
    return 2;
  }

  let result: ScanResult;
  try {
    result = scan({
      root,
      configPath: o.config ? resolve(o.config) : undefined,
      suite: o.suite as Suite | undefined,
      onlyRules: o.rule,
      runtime: o.runtime,
      threatModels: threats as ThreatModel[] | undefined,
    });
  } catch (e) {
    if (e instanceof ConfigError) {
      process.stderr.write(`gmlscan: ${e.message}\n`);
      return 2;
    }
    throw e;
  }

  const sarifOf = () => JSON.stringify(toSarif(result, { toolName: TOOL_NAME, toolVersion: VERSION, informationUri: REPOSITORY_URL, scanRoot: root }), null, 2) + "\n";
  let report: string;
  if (format === "sarif") report = sarifOf();
  else if (format === "json") report = JSON.stringify({ version: VERSION, projects: result.projects, findings: result.findings, filesScanned: result.filesScanned, durationMs: Math.round(result.durationMs) }, null, 2) + "\n";
  else report = formatText(result, { color: !o["no-color"] && !o.output && process.stdout.isTTY === true && !process.env.NO_COLOR, showPaths: o.paths });

  if (o.output) {
    mkdirSync(dirname(resolve(o.output)), { recursive: true });
    writeFileSync(o.output, report);
    process.stderr.write(`Wrote ${result.findings.length} findings to ${o.output}\n`);
  } else {
    process.stdout.write(report);
  }
  if (o.sarif) {
    mkdirSync(dirname(resolve(o.sarif)), { recursive: true });
    writeFileSync(o.sarif, sarifOf());
  }
  return exceedsThreshold(result, failOn) ? 1 : 0;
}

const invokedDirectly = process.argv[1] && /(?:cli\.(?:ts|js)|gmlscan)$/.test(process.argv[1].replace(/\\/g, "/"));
if (invokedDirectly) process.exitCode = main(process.argv.slice(2));
